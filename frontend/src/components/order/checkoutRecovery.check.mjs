await assert.rejects(submitCheckout(lock, blockedConfirmation, pending, async () => order, () => clears++), /cannot save confirmation/);
assert.equal(confirmationWrites, 1);
assert.equal(clears, 1, 'Unsaved confirmation keeps recoverable cart/request');
assert.equal(storage.getItem(PENDING_CHECKOUT), serialized);
