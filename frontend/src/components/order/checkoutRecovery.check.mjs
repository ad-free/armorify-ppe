const values = new Map();
const storage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: (key) => values.delete(key) };
const quote = { items: [{ product_id: 'product', variant_id: 'variant', quantity: 2, stock: 3, unit_price: '100000', line_total: '200000', issue: null }], subtotal: '200000', discount: '0', shipping: '30000', total: '230000', pricing_token: 'authoritative-token', can_checkout: true };
const pending = { owner_id: null, cart_revision: 'original-cart', payload: { customer_name: 'Nguyễn A', contact_phone: '0901234567', email: null, province: 'Hà Nội', district: 'Ba Đình', ward: 'Ngọc Hà', address: '12 phố A', delivery_note: 'Gọi trước', shipping_method: 'standard', payment_method: 'cod', items: [{ product_id: 'product', variant_id: 'variant', quantity: 2 }], pricing_token: quote.pricing_token, idempotency_key: 'exact-request-key' }, endpoint: '/orders/guest', quote };
const order = { id: 'confirmed-id', order_code: 'REAL-ORDER', contact_phone: '0901234567', items: [], payment_status: 'unpaid', fulfillment_status: 'unfulfilled' };
assert.equal(canSubmitQuote(quote, false, false), true);
for (const [candidate, loading, failed] of [[undefined, false, false], [quote, true, false], [quote, false, true], [{ ...quote, shipping: null }, false, false], [{ ...quote, total: null }, false, false], [{ ...quote, pricing_token: null }, false, false], [{ ...quote, can_checkout: false }, false, false], [{ ...quote, items: [] }, false, false]]) assert.equal(canSubmitQuote(candidate, loading, failed), false);
for (const line of [{ ...quote.items[0], quantity: 4 }, { ...quote.items[0], quantity: 1.5 }, { ...quote.items[0], quantity: 0 }, { ...quote.items[0], stock: 0 }, { ...quote.items[0], issue: 'Unavailable' }, { ...quote.items[0], unit_price: null }]) assert.equal(canSubmitQuote({ ...quote, items: [line] }, false, false), false);
assert.equal(readConfirmedOrder(storage), null, 'Direct success route cannot invent an order');
assert.deepEqual(readPendingCheckout(storage), { pending: null, corrupt: false });
values.set(PENDING_CHECKOUT, '{bad-json');
assert.equal(readPendingCheckout(storage).corrupt, true, 'Corruption never silently erases uncertainty');
values.clear();
let clears = 0;
let posts = 0;
const lock = { current: false };
await assert.rejects(submitCheckout(lock, { ...storage, setItem() { throw new Error('storage disabled'); } }, pending, async () => { posts++; return order; }, () => clears++), /storage disabled/);
assert.equal(posts, 0, 'Storage must succeed BEFORE POST');
assert.equal(clears, 0);
assert.equal(lock.current, false);
const serialized = JSON.stringify(pending);
await assert.rejects(submitCheckout(lock, storage, pending, async (exact) => { posts++; assert.equal(storage.getItem(PENDING_CHECKOUT), serialized, 'Exact request durably saved before POST'); assert.deepEqual(exact.payload, pending.payload); throw new TypeError('network interrupted'); }, () => clears++), /network interrupted/);
assert.equal(clears, 0, 'Ambiguous network response never clears cart');
assert.equal(storage.getItem(PENDING_CHECKOUT), serialized);
const recovered = readPendingCheckout(storage).pending;
assert.deepEqual(recovered, pending, 'Reload restores exact payload, key, endpoint and displayed quote');
let resolve;
const first = submitCheckout(lock, storage, recovered, (exact) => { posts++; assert.equal(exact.payload.idempotency_key, 'exact-request-key'); assert.deepEqual(exact.payload, pending.payload); return new Promise((done) => { resolve = done; }); }, () => clears++);
const overlapping = submitCheckout(lock, storage, recovered, async () => { throw new Error('Double POST'); }, () => clears++);
assert.equal(await overlapping, null, 'Same-turn duplicate submit is locked');
assert.equal(clears, 0);
resolve(order);
assert.deepEqual(await first, order);
assert.equal(posts, 2, 'Only one ambiguous POST and one same-key recovery POST');
assert.equal(clears, 1, 'Only confirmed server response clears cart');
assert.equal(storage.getItem(PENDING_CHECKOUT), null);
assert.deepEqual(readConfirmedOrder(storage), order, 'Confirmation survives reload');
assert.equal(storage.getItem(CONFIRMED_ORDER), JSON.stringify(order));
assert.equal(isDefinitiveRejection(422, []), true);
assert.equal(isDefinitiveRejection(409, [{ type: 'stale_pricing', loc: ['body', 'pricing_token'] }]), true);
assert.equal(isDefinitiveRejection(409, [{ type: 'checkout_unavailable', loc: ['body', 'items', 0, 'quantity'] }]), true);
assert.equal(isDefinitiveRejection(503, [{ type: 'shipping_unavailable' }]), true);
assert.equal(isDefinitiveRejection(409, [{ type: 'idempotency_conflict' }]), false, 'Do not rotate keys on conflict');
for (const status of [401, 408, 429, 500, 502, 504]) assert.equal(isDefinitiveRejection(status, 'unknown'), false);
values.clear();
